// Writes the header of each vocab/<type>.ts (what the type is, how it's matched,
// and the tags rls already has), creating missing files. Entries below the
// header are kept as they are. Run after updating rls/taginfo/taginfo.csv:
//   node new_parser/scripts/gen-vocab.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const csv = readFileSync(join(root, 'rls/taginfo/taginfo.csv'), 'utf8');

// type → [what it fills and examples, how it's matched]
const TYPES = {
  arch: ['CPU architectures for apps: fills `arch`, e.g. x64, ARM64.', 'Matched as a whole word anywhere, ignoring case.'],
  audio: ['Audio formats: fills `audio` (a list), e.g. DDP, DTS-HD.MA, FLAC.', 'Matched anywhere, ignoring case, and may be followed by channels (DDP5.1) or a codec (DDP5.1H264).'],
  bitdepth: ['Video bit depth: fills `bitDepth`, e.g. 10BIT.', 'Matched as a whole word anywhere, ignoring case.'],
  channels: ['Audio channels: fills `channels`, e.g. 5.1, 7.1.', 'Matched as a whole word anywhere, ignoring case; also read right after an audio tag (DDP5.1). Reported as its digits with a dot after the first (5.1), so write the tag that way.'],
  codec: ['Video codecs: fills `codec` (a list), e.g. x264, HEVC, AV1.', 'Matched anywhere, ignoring case, ending at a word boundary or separator.'],
  collection: ['Streaming services, networks and collections: fills `collection`, e.g. AMZN, NF, IMAX.', 'Matched anywhere, ignoring case, ending at a word boundary or separator.'],
  container: ['File containers: fills `container`, e.g. MKV, EPUB.', 'Matched as a whole word anywhere, ignoring case.'],
  cut: ["Cuts of a film: fills `cut` (a list), e.g. Directors.Cut, Extended.", 'Matched as a whole word anywhere, ignoring case.'],
  edition: ['Editions: fills `edition` (a list), e.g. Remastered.Edition, Open.Matte.', 'Matched as a whole word anywhere, ignoring case.'],
  ext: ['File extensions: fills `ext`, e.g. mkv, mp4.', "Matched only at the very end of the name, after a '.', ignoring case. Reported in lower case."],
  genre: ['Genres: fills `genre`, e.g. Anime, Documentary.', "Matched in parentheses, as '(Rock)'. The optional `other` regexp is a second form also matched as a bare word (rls: Documentary has (?-i:DO[CK]U?) for DOC and DOKU)."],
  group: ['Release groups: fills `group`, e.g. CODEX.', "Matched only at the end of the name, after any separator. Unlisted groups are still read from the text after the last '-'; listing one also finds it without a dash ('…h264.GRP') and keeps a dash inside its name ('D-Z0N3'). A listed group also counts at the very start in brackets, fansub style ('[SubsPlease] Title - 04 (1080p)'), where rls would read it as the site. The group comes out as written in the name."],
  hdr: ['HDR formats: fills `hdr` (a list), e.g. DV, HDR10+.', 'Matched anywhere, ignoring case, ending at a word boundary or separator.'],
  language: ['Languages: fills `language` (a list), e.g. GERMAN, MULTi.', 'Matched as a whole word anywhere, CASE-SENSITIVE: write the tag in the case it appears in names, or give a `match` with (?i) for any case.'],
  other: ['Other tags: fills `other` (a list), e.g. PROPER, REPACK, INTERNAL.', "Matched as a whole word anywhere, ignoring case. The optional `other` is a suffix also read when glued to the group with '_' (rls: INTERNAL has int, for '-GRP_INT')."],
  platform: ['Platforms for apps and games: fills `platform`, e.g. Win64, PS5.', 'Matched as a whole word anywhere, ignoring case.'],
  region: ['Regions: fills `region`, e.g. R1, EUR, USA.', 'Matched as a whole word anywhere, ignoring case.'],
  resolution: ['Resolutions: fills `resolution`, e.g. 1080p, 2160p.', 'Matched as a whole word anywhere, ignoring case.'],
  size: ['Disc sizes: fills `size`, e.g. DVD5, BD50.', "Matched as a whole word anywhere, ignoring case. Reported in upper case with 'i' for 'I', as rls writes sizes: a tag 'Mini' comes out as 'MiNi'."],
  source: ['Sources: fills `source`, e.g. WEB-DL, BluRay, HDTV.', 'Matched as a whole word anywhere, ignoring case.'],
};

const START = '// ---- generated by scripts/gen-vocab.mjs; edit below the end marker ----';
const END = '// ---- end of generated header ----';

const tags = {};
for (const line of csv.split('\n').slice(1)) {
  const i = line.indexOf(',');
  if (i < 0) continue;
  const typ = line.slice(0, i);
  const tag = line.slice(i + 1, line.indexOf(',', i + 1));
  (tags[typ] ??= []).push(tag);
}
const unknown = Object.keys(tags).filter((t) => !TYPES[t]);
if (unknown.length) throw new Error('taginfo.csv has types without a vocab file: ' + unknown.join(', '));

const wrap = (words, width = 112) => {
  const lines = [];
  let cur = '';
  for (const w of words) {
    if (cur && cur.length + 2 + w.length > width) {
      lines.push(cur + ',');
      cur = w;
    } else cur = cur ? cur + ', ' + w : w;
  }
  if (cur) lines.push(cur);
  return lines.map((l) => '//   ' + l);
};

const wrapText = (text, width = 116) => {
  const lines = [];
  let cur = '';
  for (const w of text.split(' ')) {
    if (cur && cur.length + 1 + w.length > width) {
      lines.push(cur);
      cur = w;
    } else cur = cur ? cur + ' ' + w : w;
  }
  if (cur) lines.push(cur);
  return lines.map((l) => '// ' + l);
};

for (const [typ, [what, how]] of Object.entries(TYPES)) {
  const have = [...(tags[typ] ?? [])].sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }));
  const withOther = typ === 'genre' || typ === 'other';
  const header = [
    START,
    ...wrapText(what),
    ...wrapText(how),
    '//',
    '// Add one entry per tag; the fields are described in types.ts. The parser picks the list up the next time it is',
    '// built (an app reload). Entries are tried after rls\'s own. To add spellings to a tag rls already has, give',
    '// that tag with `aliases` (its pattern in taginfo.csv shows the spellings rls already reads).',
    '//',
    `// rls already has ${have.length} (rls/taginfo/taginfo.csv):`,
    ...wrap(have),
    END,
  ].join('\n');
  const body = withOther
    ? "import type { VocabEntryWithOther } from './types';\n\nexport const entries: VocabEntryWithOther[] = [];\n"
    : "import type { VocabEntry } from './types';\n\nexport const entries: VocabEntry[] = [];\n";
  const file = join(root, 'vocab', typ + '.ts');
  let rest = body;
  if (existsSync(file)) {
    const old = readFileSync(file, 'utf8');
    const k = old.indexOf(END);
    if (old.indexOf(START) !== 0 || k < 0) throw new Error(`${file}: header markers missing, not touching it`);
    rest = old.slice(k + END.length).replace(/^\n+/, '');
  }
  writeFileSync(file, header + '\n\n' + rest);
}
console.log('wrote', Object.keys(TYPES).length, 'vocab files');
